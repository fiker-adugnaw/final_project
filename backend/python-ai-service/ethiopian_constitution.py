# ============================================
# FUNCTION TO GET CONSTITUTION ARTICLE
# ============================================

def get_constitution_article(article_number):
    """
    Get a specific article from the Ethiopian Constitution
    """
    for chapter_num, chapter in ETHIOPIAN_CONSTITUTION["chapters"].items():
        if str(article_number) in chapter["articles"]:
            article = chapter["articles"][str(article_number)]
            return {
                "chapter": chapter["title"],
                "article": article_number,
                "title": article["title"],
                "content": article["content"]
            }
    return None

# ============================================
# FUNCTION TO SEARCH CONSTITUTION
# ============================================

def search_constitution(query):
    """
    Search the constitution for relevant articles
    """
    results = []
    query_lower = query.lower()
    
    for chapter_num, chapter in ETHIOPIAN_CONSTITUTION["chapters"].items():
        for art_num, article in chapter["articles"].items():
            if (query_lower in article["title"].lower() or 
                query_lower in article["content"].lower()):
                results.append({
                    "chapter": chapter["title"],
                    "article": art_num,
                    "title": article["title"],
                    "content": article["content"][:200] + "..."
                })
    return results

# ============================================
# FUNCTION TO GET LEGAL CODE REFERENCE
# ============================================

def get_legal_code_reference(code_name, reference=None):
    """
    Get reference from Ethiopian legal codes
    """
    if code_name in ETHIOPIAN_LEGAL_CODES:
        code = ETHIOPIAN_LEGAL_CODES[code_name]
        if reference:
            return {
                "name": code["name"],
                "reference": reference,
                "context": f"Under {code['name']}, {reference}"
            }
        return code
    return None

# ============================================
# FUNCTION TO CHECK IF QUERY IS ETHIOPIAN LEGAL
# ============================================

def is_ethiopian_legal_query(query):
    """
    Check if a query relates to Ethiopian law
    """
    query_lower = query.lower()
    
    # Check English keywords
    for keyword in ETHIOPIAN_LEGAL_KEYWORDS["english"]:
        if keyword in query_lower:
            return True, keyword
    
    # Check Amharic keywords
    for keyword in ETHIOPIAN_LEGAL_KEYWORDS["amharic"]:
        if keyword in query:
            return True, keyword
    
    # Check regions
    for region in ETHIOPIAN_REGIONS:
        if region.lower() in query_lower:
            return True, region
    
    # Check cities
    for city in ETHIOPIAN_CITIES:
        if city.lower() in query_lower:
            return True, city
    
    # Check institutions
    for institution in ETHIOPIAN_LEGAL_INSTITUTIONS:
        if institution.lower() in query_lower:
            return True, institution
    
    return False, None

